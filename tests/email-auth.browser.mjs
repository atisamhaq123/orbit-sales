import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';

const browser = await chromium.launch({executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true});
const base = process.env.TEST_URL || 'http://localhost:3100';
try {
  const page = await browser.newPage();
  const requests = [], errors = [];
  let allowLogin = false;
  const user = {id: '00000000-0000-0000-0000-000000000099', email: 'signup@example.test', aud: 'authenticated', app_metadata: {provider: 'email'}, user_metadata: {}, identities: [], created_at: new Date().toISOString()};
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/auth/v1/**', async route => {
    const request = route.request();
    if (request.method() === 'OPTIONS') return route.fulfill({status: 204, headers: {'access-control-allow-origin': '*', 'access-control-allow-headers': '*'}});
    requests.push({url: request.url(), body: request.postDataJSON()});
    const signup = new URL(request.url()).pathname.endsWith('/signup');
    const token = `${Buffer.from(JSON.stringify({alg: 'HS256', typ: 'JWT'})).toString('base64url')}.${Buffer.from(JSON.stringify({sub: user.id, exp: Math.floor(Date.now()/1000) + 3600})).toString('base64url')}.mock-signature`;
    const payload = signup ? user : allowLogin ? {access_token: token, refresh_token: 'mock-refresh-token', token_type: 'bearer', expires_in: 3600, user} : {code: 'invalid_credentials', msg: 'Invalid login credentials'};
    await route.fulfill({status: signup || allowLogin ? 200 : 400, contentType: 'application/json', headers: {'access-control-allow-origin': '*'}, body: JSON.stringify(payload)});
  });
  await page.goto(`${base}/login?next=${encodeURIComponent('/invite/test-token')}`);
  await page.getByLabel('Email address').fill('login@example.test');
  await page.getByLabel('Password', {exact: true}).fill('test-password');
  await page.getByRole('button', {name: 'Log in', exact: true}).click();
  await page.getByRole('alert').filter({hasText: 'Invalid login credentials'}).waitFor();
  assert.equal(requests[0].body.email, 'login@example.test');
  assert.match(requests[0].url, /grant_type=password/);
  await page.getByRole('link', {name: 'Create an account'}).click();
  assert.equal(new URL(page.url()).searchParams.get('next'), '/invite/test-token');
  await page.getByLabel('Full name').fill('Email Test');
  await page.getByLabel('Email address').fill('signup@example.test');
  await page.getByLabel('Password', {exact: true}).fill('test-password');
  await page.getByLabel('Confirm password').fill('wrong-password');
  await page.getByRole('button', {name: 'Create account', exact: true}).click();
  await page.getByRole('alert').filter({hasText: 'Passwords do not match'}).waitFor();
  assert.equal(requests.length, 1, 'Mismatched passwords never reach Supabase');
  await page.getByLabel('Confirm password').fill('test-password');
  await page.getByRole('button', {name: 'Create account', exact: true}).click();
  await page.getByRole('status').filter({hasText: 'Check your inbox'}).waitFor();
  assert.equal(requests[1].body.data.full_name, 'Email Test');
  const callback = new URL(new URL(requests[1].url).searchParams.get('redirect_to'));
  assert.equal(callback.pathname, '/auth/callback');
  assert.equal(callback.searchParams.get('next'), '/invite/test-token');
  await page.goto(`${base}/login?next=https://example.com`);
  assert.equal(new URL(await page.getByRole('link', {name: 'Create an account'}).getAttribute('href'), base).searchParams.get('next'), '/app');
  await page.goto(base);
  assert.equal(await page.locator('a[href*="/auth/google"]').count(), 0);
  assert.equal(await page.locator('a[href="/login"]').count(), 1);
  assert.ok(await page.locator('a[href="/signup"]').count() > 0);
  allowLogin = true;
  await page.route(`${base}/app?demo=1`, route => route.fulfill({contentType: 'text/html', body: '<h1>Authenticated destination</h1>'}));
  await page.goto(`${base}/login?next=${encodeURIComponent('/app?demo=1')}`);
  await page.getByLabel('Email address').fill('signup@example.test');
  await page.getByLabel('Password', {exact: true}).fill('test-password');
  await page.getByRole('button', {name: 'Log in', exact: true}).click();
  await page.getByRole('heading', {name: 'Authenticated destination'}).waitFor();
  assert.equal(new URL(page.url()).pathname, '/app');
  assert.ok((await page.context().cookies()).some(cookie => cookie.name.includes('auth-token')), 'Password login writes Supabase session cookies');
  assert.deepEqual(errors, []);
  console.log('Email auth browser checks passed: password login success/session cookies and errors, signup, confirmation message, password validation, invitation destination, safe redirects, landing links. Supabase HTTP responses were mocked; no accounts or emails created.');
} finally { await browser.close(); }
